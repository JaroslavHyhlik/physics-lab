import { test, expect } from '@playwright/test';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { READY } from './ready';

/**
 * Inventory: opens every simulation and lists its controls into docs/inventory.md.
 * Run on its own with:  npx playwright test tests/e2e/inventory.spec.ts --project=desktop
 */
const OUT = 'docs/inventory.md';

interface Inv {
  id: string;
  title: string;
  sliders: string[];
  segmented: string[];
  toggles: string[];
  buttons: string[];
  presets: string[];
  transport: boolean;
  tools: string[];
  graphs: string[];
  canvas: string;
}

test.describe.configure({ mode: 'serial' });
const all: Inv[] = [];

for (const id of READY) {
  test(`inventory ${id}`, async ({ page }, info) => {
    test.skip(!process.env.AUDIT, 'long audit: run with npm run test:audit');
    test.skip(info.project.name !== 'desktop');
    await page.goto(`/#/sim/${id}`);
    await expect(page.locator('.stage canvas')).toBeVisible();
    const inv = await page.evaluate(() => {
      const t = (el: Element | null) => (el?.textContent ?? '').replace(/\s+/g, ' ').trim();
      const pane = document.querySelector('.side .pane:not([hidden])')!;
      const sliders = [...pane.querySelectorAll('.slider')].map((s) => `${t(s.querySelector('label'))} [${t(s.querySelector('.unit')) || '–'}]`);
      const segmented = [...pane.querySelectorAll('.wrap')].map(
        (w) => `${t(w.querySelector('.label')) || 'choice'}: ${[...w.querySelectorAll('[role=radio]')].map((b) => t(b)).join(' / ')}`,
      );
      const toggles = [...pane.querySelectorAll('label.toggle')].map((l) => t(l.querySelector('.label')));
      const buttons = [...pane.querySelectorAll('button')]
        .filter((b) => !b.closest('.slider') && !b.closest('.wrap') && !b.closest('label.toggle'))
        .map((b) => t(b) || b.getAttribute('aria-label') || '?');
      const presets = [...document.querySelectorAll('.preset select option')].map((o) => t(o)).filter((x) => x && x !== 'Presets');
      const tools = [...document.querySelectorAll('.tools button')].map((b) => b.getAttribute('aria-label') || t(b));
      const graphs = [...document.querySelectorAll('.graphs .chip')].map((b) => t(b));
      return {
        title: t(document.querySelector('.bar h1, .bar .title')),
        sliders,
        segmented,
        toggles,
        buttons,
        presets,
        transport: !!document.querySelector('.transport button'),
        tools,
        graphs,
      };
    });
    const src = readFileSync(`src/sims/${id}/Sim.svelte`, 'utf8') + (existsSync(`src/sims/${id}/render.ts`) ? readFileSync(`src/sims/${id}/render.ts`, 'utf8') : '');
    const canvas = /interaction=\{/.test(src) ? (/move:\s*\(\)\s*=>\s*\{\s*\}/.test(src) ? 'tap to select' : 'drag / tap') : '—';
    all.push({ id, ...inv, canvas });
  });
}

test.afterAll(() => {
  if (!all.length) return;
  const lines = [
    '# Inventory of simulations and controls',
    '',
    `Generated by \`tests/e2e/inventory.spec.ts\` (${all.length} simulations). Every simulation also has: Controls/Info tabs, a theme switch, the Info panel (formulas, assumptions), and keyboard shortcuts.`,
    '',
    '**Mobile sensor lab (`#/lab`)**: not built yet (placeholder page “soon”, phase 4 deferred).',
    '',
  ];
  for (const s of all) {
    lines.push(`## ${s.id} — ${s.title}`);
    const row = (k: string, v: string[] | string) => {
      const x = Array.isArray(v) ? v.join('; ') : v;
      if (x) lines.push(`- **${k}:** ${x}`);
    };
    row('Sliders (each also has a typed-value field)', s.sliders);
    row('Choices', s.segmented);
    row('Switches', s.toggles);
    row('Buttons', s.buttons);
    row('Presets', s.presets.length ? `${s.presets.length}: ${s.presets.join('; ')}` : '');
    row('Play / pause / step / reset / speed', s.transport ? 'yes' : 'no (static)');
    row('Measuring tools', s.tools);
    row('Graphs (+ CSV export)', s.graphs);
    row('Canvas', s.canvas);
    lines.push('');
  }
  writeFileSync(OUT, lines.join('\n'));
});
